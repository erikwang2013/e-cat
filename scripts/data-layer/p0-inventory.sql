-- P0 data-layer baseline inventory (read-only, MySQL 8.4/9).
-- p0-inventory.sh prints each section header, then runs that section's statements.
-- Sections: VERSION, AUTH_PLUGINS, TABLES, INDEXES, SLOW_QUERIES, LOCKS, REPLICATION, PARTITIONS.

-- SECTION: VERSION
SELECT VERSION() AS version;

-- SECTION: AUTH_PLUGINS
-- 9.x 已无 mysql_native_password；出现该插件说明账号仍需迁移。
SELECT user, host, plugin FROM mysql.user ORDER BY user, host;

-- SECTION: TABLES
SELECT TABLE_NAME, TABLE_ROWS, DATA_LENGTH, INDEX_LENGTH
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_TYPE = 'BASE TABLE'
ORDER BY DATA_LENGTH + INDEX_LENGTH DESC;

-- SECTION: INDEXES
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COLUMN_NAME, CARDINALITY
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;

-- SECTION: SLOW_QUERIES
SELECT SCHEMA_NAME, DIGEST_TEXT, COUNT_STAR, SUM_TIMER_WAIT, AVG_TIMER_WAIT,
       SUM_ROWS_EXAMINED, SUM_ROWS_SENT, SUM_NO_INDEX_USED, FIRST_SEEN, LAST_SEEN
FROM performance_schema.events_statements_summary_by_digest
WHERE DIGEST_TEXT IS NOT NULL
ORDER BY SUM_TIMER_WAIT DESC
LIMIT 20;

-- SECTION: LOCKS
SELECT w.ENGINE, w.REQUESTING_THREAD_ID, w.REQUESTING_ENGINE_TRANSACTION_ID,
       w.BLOCKING_THREAD_ID, w.BLOCKING_ENGINE_TRANSACTION_ID,
       b.OBJECT_SCHEMA, b.OBJECT_NAME, b.INDEX_NAME,
       b.LOCK_TYPE, b.LOCK_MODE, b.LOCK_STATUS, b.LOCK_DATA
FROM performance_schema.data_lock_waits AS w
JOIN performance_schema.data_locks AS b
  ON b.ENGINE_LOCK_ID = w.BLOCKING_ENGINE_LOCK_ID
ORDER BY w.REQUESTING_THREAD_ID;

-- SECTION: REPLICATION
SHOW REPLICA STATUS;

-- SECTION: PARTITIONS
SELECT TABLE_NAME, PARTITION_NAME, PARTITION_METHOD, PARTITION_EXPRESSION,
       PARTITION_DESCRIPTION, TABLE_ROWS, DATA_LENGTH
FROM information_schema.PARTITIONS
WHERE TABLE_SCHEMA = DATABASE()
  AND PARTITION_NAME IS NOT NULL
ORDER BY TABLE_NAME, PARTITION_ORDINAL_POSITION;
